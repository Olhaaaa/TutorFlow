/**
 * Відкладені доставки: що саме коміт лишає для сусіднього сервіса.
 *
 * У моноліті цього файлу не було б потрібно взагалі. Там бронювання — одна
 * транзакція з двох частин: слот змінюється й кошти списуються разом, і або
 * обидві частини є, або немає жодної. Коли в кожного сервіса власна база,
 * спільної транзакції не існує, і лишається вибір: або віддати перевагу
 * доступності й записати слот, не знаючи, чи пішли гроші, або писати в СВОЮ
 * базу разом зі слотом ЗАВДАННЯ на рух коштів.
 *
 * Друге і є outbox: рядок завдання вставляється тією самою транзакцією, що й
 * зміна слота, тому неможливий стан «слот заброньований, а про гроші ніхто не
 * дізнається». Доставка at-least-once (рядок живе, доки сусід не підтвердив),
 * а від повторного застосування захищає `opId` на боці отримувача.
 *
 * Події шини через цей журнал НЕ йдуть, і це свідомо. Подія публікується після
 * коміту, бо описує вже зафіксований факт; щоб покласти її в outbox, виклик
 * довелося б перенести ВСЕРЕДИНУ транзакції — тобто пообіцяти факт, який ще
 * може відкотитись. Тому нагадування лишаються at-most-once, як у лабі 2, і
 * від втрати їх страхує вікно нагадувань, а не доставка.
 */
import type { CredentialUpsert, MoneyTransfer, StudentContact, TeacherProfile } from './internal.js';

export type OutboxKind =
  /** Розклад → білінг: списати за заняття. */
  | 'billing.charge'
  /** Розклад → білінг: повернути кошти за заняття. */
  | 'billing.refund'
  /** Білінг → розклад: закрити найближчі неоплачені заняття. */
  | 'scheduling.apply_payment'
  /** Білінг → вхід: зʼявився студент, йому потрібні реквізити входу. */
  | 'identity.credential'
  /** Білінг → нагадування: контакт студента для каналу доставки. */
  | 'notifications.contact'
  /** Вхід → розклад: зареєструвався викладач, потрібні зона й ціна. */
  | 'scheduling.teacher'
  /** Вхід → білінг: той самий викладач, потрібне імʼя для журналу. */
  | 'billing.teacher';

/** Завдання з журналу у розібраному вигляді. Дискримінант — kind. */
export type OutboxJob =
  | { kind: 'billing.charge'; payload: MoneyTransfer }
  | { kind: 'billing.refund'; payload: MoneyTransfer }
  | { kind: 'scheduling.apply_payment'; payload: { opId: string; studentId: number } }
  | { kind: 'identity.credential'; payload: CredentialUpsert }
  | { kind: 'notifications.contact'; payload: StudentContact }
  | { kind: 'scheduling.teacher'; payload: TeacherProfile }
  | { kind: 'billing.teacher'; payload: TeacherProfile };

/**
 * Чим скінчилась спроба доставки.
 *
 * Три стани, бо лікуються вони по-різному. `done` — підтверджено, рядок
 * закривається. `retry` — сусід не відповів, спробуємо пізніше: рядок
 * лишається, і саме через це нічого не губиться. `compensate` — сусід
 * ВІДМОВИВ назавжди (коштів не вистачило), тому повторювати немає сенсу, а
 * натомість треба відкотити наслідок у власній базі.
 */
export type OutboxOutcome = 'done' | 'retry' | 'compensate';
