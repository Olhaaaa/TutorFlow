/**
 * МЕЖА З БОКУ ГРОШЕЙ. Оголошена білінгом, реалізується розкладом — тобто
 * дзеркало ChargePort, і саме через це межа між вертикалями замкнена: ніхто не
 * імпортує нутрощі сусіда, обидва знають лише інтерфейс.
 *
 * Білінгу потрібні від розкладу дві речі, і обидві — не його дані.
 *
 * Перша: які заняття студента ще не оплачені. З них рахується борг у кабінеті
 * (`dueMinor`), і вони ж показуються списком «лишилось заплатити».
 *
 * Друга: закрити найближчі неоплачені заняття грошима, які щойно надійшли.
 * Це змінює СТАН СЛОТА, тобто чужі дані, тому білінг не робить цього сам —
 * він просить. У моноліті прохання виконується в тій самій транзакції, що й
 * зарахування коштів; коли в розкладу власна база, транзакція обривається тут,
 * і замість виклику лишається запис у outbox.
 */
export interface LessonsPort {
  /**
   * Неоплачені заняття студента в ХРОНОЛОГІЧНОМУ порядку: закриваються вони
   * найближчими вперед, і порядок — частина правила, а не подробиця запросу.
   */
  pendingPayment(
    studentId: number,
    tx?: Executor,
  ): Promise<{ slotId: number; startAt: string; priceMinor: number }[]>;

  /**
   * Закрити неоплачені заняття, які покриває баланс.
   *
   * `tx` обовʼязковий: у моноліті зарахування коштів і закриття занять — одна
   * транзакція, і розірвати її не можна. Повертає слоти, які стали
   * оплаченими, — саме їх показує відповідь на поповнення.
   */
  applyPayment(tx: Executor, studentId: number): Promise<number[]>;
}

