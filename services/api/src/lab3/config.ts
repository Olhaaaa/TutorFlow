import { optional, required } from '../config.js';

/**
 * Оточення, яке зʼявляється ЛИШЕ в мікросервісній композиції.
 *
 * Межа між сервісами — це адреса сусіда й спільний секрет, і більше нічого.
 * Жодної реєстрації, жодного service discovery: усередині мережі Compose
 * імена сервісів розводить власний DNS, а в лабораторній 4 те саме зробить
 * Service у Kubernetes. Доки адреса приходить з оточення, обидва випадки
 * виглядають для коду однаково.
 *
 * Адреси необовʼязкові навмисно: сервісу білінгу не потрібна адреса входу, і
 * вимагати її означало б змушувати compose описувати звʼязки, яких немає.
 * Відсутню адресу ловить той виклик, який її потребує, і повідомлення в нього
 * конкретне.
 */
export const lab3 = {
  /** Де чекати запросів. Усі сервіси слухають один порт — різні лише контейнери. */
  port: Number(process.env.PORT ?? 8080),

  peers: {
    identity: optional('IDENTITY_URL'),
    scheduling: optional('SCHEDULING_URL'),
    billing: optional('BILLING_URL'),
    notifications: optional('NOTIFICATIONS_URL'),
  },

  /**
   * Спільний секрет внутрішніх маршрутів.
   *
   * Він не замінює автентифікацію користувача — її робить токен, і кожен
   * сервіс перевіряє його сам. Цей заголовок відповідає на інше питання: чи
   * прийшов запрос від сусіднього сервіса, а не з інтернету. Внутрішні порти
   * назовні не публікуються взагалі, тому секрет тут — другий рубіж, а не
   * перший.
   *
   * Без значення внутрішні маршрути відкриті, і це режим для локального
   * запуску: інакше `curl` до сервіса вимагав би спершу знайти токен.
   */
  internalToken: optional('INTERNAL_TOKEN'),

  /**
   * Крок дренажу журналу відкладених доставок у воркері.
   *
   * Це не частота доставки — доставку робить той процес, який зробив коміт,
   * одразу й синхронно. Це частота, з якою підбирається те, що з першої
   * спроби не доїхало: сусід перезапускався, мережа мигнула.
   */
  outboxIntervalMs: Number(process.env.OUTBOX_INTERVAL_MS ?? 2000),

  /** Таймаут внутрішнього виклику. Довше чекати немає за чим: є повтор. */
  internalTimeoutMs: Number(process.env.INTERNAL_TIMEOUT_MS ?? 3000),
};

/** Адреса сусіда або зрозуміла відмова. */
export function peerUrl(name: keyof typeof lab3.peers): string {
  const url = lab3.peers[name];
  if (!url) {
    throw new Error(
      `не задано адресу сервіса ${name} — очікується ${name.toUpperCase()}_URL`,
    );
  }
  return url.replace(/\/+$/, '');
}

/** Для сервісів, яким потрібні всі чотири бази (скид демо-даних). */
export function databaseUrlFor(role: string): string {
  return required(`DATABASE_URL_${role.toUpperCase()}`);
}
