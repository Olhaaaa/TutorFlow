import { randomUUID } from 'node:crypto';

/**
 * Ключ операції — те, чим отримувач розпізнає повторну доставку.
 *
 * Чому випадковий, а не складений з даних. Ключ зі слота й виду («списати за
 * слот 42») виглядає привабливо, бо не вимагає нічого зберігати, але бреше:
 * студент бронює й скасовує ту саму годину по колу, і друге повернення за
 * слот 42 — законна операція, а не повтор. Ключ мусить ідентифікувати
 * ОПЕРАЦІЮ, а операція — це подія в часі, а не стан.
 *
 * Видається рівно один раз, у тій самій транзакції, що й зміна слота, і далі
 * живе в рядку журналу. Повтори доставки несуть той самий ключ, тому
 * отримувач застосовує рух коштів один раз, скільки б разів йому його не
 * надіслали.
 */
export function newOpId(): string {
  return randomUUID();
}
