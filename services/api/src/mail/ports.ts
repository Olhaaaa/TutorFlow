/**
 * МЕЖА ПОШТИ. Оголошена тим, хто надсилає, реалізується транспортом.
 *
 * Причина та сама, що й у решти портів застосунку: домен не повинен знати,
 * чим саме доставляється лист. Тут вона має ще одну сторону — у лабораторних
 * робочого SMTP може не бути взагалі, і застосунок мусить лишатись
 * перевірюваним. Тому реалізацій дві: справжній SMTP і запис у лог, і друга
 * вмикається сама, коли транспорт не налаштований.
 *
 * Лист описується ПРОСТО: кому, тема, текст і необовʼязковий HTML. Ні
 * вкладень, ні копій, ні черги — усе, чого тут немає, додається тоді, коли
 * знадобиться, а не наперед.
 */
export interface MailMessage {
  to: string;
  subject: string;
  /** Обовʼязковий: лист без текстової частини частіше потрапляє у спам. */
  text: string;
  html?: string;
}

export interface MailPort {
  /**
   * Надіслати лист.
   *
   * Кидає, якщо транспорт відмовив. Той, хто викликає, вирішує сам, чи це
   * привід відмовити користувачеві: на реєстрації — ні (акаунт уже
   * створений, лист можна перепросити), на відновленні пароля — теж ні, бо
   * відповідь однакова незалежно від результату.
   */
  send(message: MailMessage): Promise<void>;

  /** Чи налаштований справжній транспорт. Видно в /healthz і в логах. */
  readonly configured: boolean;
}

