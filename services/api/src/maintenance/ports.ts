/**
 * МЕЖА ПРОХОДУ ПЕРЕХОДІВ. Оголошена проходом, реалізується платежами.
 *
 * Прохід робить три речі, які тягне час: звільняє неоплачені закріплення,
 * закриває проведені заняття й протерміновує рахунки, за якими не заплатили.
 * Перші дві — розклад, третя — гроші, і вона єдина, що виходить за межу
 * вертикалі.
 *
 * Доки все жило в одному процесі, прохід просто кликав репозиторій платежів.
 * Коли в білінгу власна база, цей виклик перетворюється на запрос по HTTP —
 * або, у сервісі розкладу без доступу до платежів, на нуль. Порт лишає прохід
 * без знання про те, який з двох випадків зараз.
 */
export interface PaymentsExpiryPort {
  /**
   * Протермінувати рахунки, старші за вказану кількість хвилин.
   *
   * @returns скільком рахункам це стосувалось.
   */
  expirePending(validityMinutes: number): Promise<number>;
}

