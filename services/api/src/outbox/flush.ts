import { Injectable } from '@nestjs/common';

/**
 * ТОЧКА, У ЯКІЙ ДВІ АРХІТЕКТУРИ РОЗХОДЯТЬСЯ.
 *
 * Виклик `flush()` стоїть рівно там, де щойно завершилась транзакція, яка
 * могла залишити завдання в журналі outbox: після бронювання, скасування,
 * переносу, поповнення.
 *
 * У моноліті він НЕ РОБИТЬ НІЧОГО — і це правильно: там зміна слота й рух
 * коштів відбулись однією транзакцією, відкладати нічого. У мікросервісах той
 * самий рядок перетворює локальний коміт у запрос до сусіднього сервіса.
 *
 * Чому виклик явний, а не схований у підписці на коміт: він мусить бути
 * ВИДНИМ. Читач коду має бачити, де саме закінчується гарантія бази й
 * починається гарантія доставки — інакше різниця між двома архітектурами
 * лишається в компоузі, а в коді її немає.
 *
 * Помилка доставки назовні не піднімається: завдання вже записане в базу, і
 * його доля — справа дренажу, а не того, хто чекає відповіді.
 */
export interface OutboxFlush {
  flush(): Promise<void>;
}

export const OUTBOX_FLUSH = 'OUTBOX_FLUSH';

/** Реалізація для моноліту: відкладати нічого, бо транзакція була спільна. */
@Injectable()
export class NoopOutboxFlush implements OutboxFlush {
  async flush(): Promise<void> {
    /* навмисно порожньо — див. коментар до OutboxFlush */
  }
}
